// ==========================================
// JavaScript Variables
// ==========================================

// const is used when the value should not be reassigned
const employeeName = "Rahul";

// let is used when the value can change
let employeeSalary = 400000;

// Display the values
console.log("Employee Name:", employeeName);
console.log("Employee Salary:", employeeSalary);


// Change the value of a let variable
employeeSalary = 450000;

console.log("Updated Salary:", employeeSalary);